#!/usr/bin/env node
// Generates src/data/warehouseSheetOrder.ts from scripts/data/warehouse-codes.csv — a real-world
// request: "การปริ้นใบเบิก ให้ชื่อยาตามลำดับเหมือน gg sheet ให้ครบถ้วน". printPickListSheet
// (utils/print.ts) sorts by shelf bin by default — correct for the floor-fill checklists, where
// walking shelf-to-shelf in physical order is the point, but wrong for
// printWarehouseRequestByCategory (AppContext.tsx), which the user wants to read in the SAME row
// order warehouse staff already know from the original Google Sheet, not re-sorted by this
// app's own shelf layout.
//
// warehouse-codes.csv (scripts/data/) already preserves the hospital's 4 sheets' own original
// row order (one code per row, grouped by category, never reordered since it was first
// exported — see backfill-warehouse-codes.mjs's own header comment). This script turns that row
// order into a plain whCode -> index lookup table, committed as a real source file (not
// generated at build/runtime) so it ships in the client bundle without bundling the CSV parser
// or the CSV itself into the app. Re-run this whenever warehouse-codes.csv changes.
//
// Usage: node scripts/generate-warehouse-order.mjs

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_FILE = join(__dirname, 'data', 'warehouse-codes.csv');
const OUT_FILE = join(__dirname, '..', 'src', 'data', 'warehouseSheetOrder.ts');

function parseCsvLine(line) {
  const out = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQuotes = false; }
      else cur += ch;
    } else if (ch === '"') inQuotes = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const text = readFileSync(DATA_FILE, 'utf8');
const lines = text.split(/\r?\n/).filter((l) => l.length > 0);
const codes = lines.slice(1).map((line) => parseCsvLine(line)[0].trim()).filter(Boolean);

// A handful of codes appear on more than one row in the source sheet itself (a real data-quality
// issue in the hospital's own CSV, documented in backfill-warehouse-codes.mjs's own header
// comment — e.g. 1400091 used for both "Calcium gluconate" and "Digoxin inj") — first occurrence
// wins (an object literal can't repeat a key anyway), which is also the one
// backfill-warehouse-codes.mjs itself would have matched first.
const seen = new Set();
const entries = [];
codes.forEach((code, i) => {
  if (seen.has(code)) return;
  seen.add(code);
  entries.push(`  ${JSON.stringify(code)}: ${i},`);
});
const entriesStr = entries.join('\n');
const out = `// GENERATED by scripts/generate-warehouse-order.mjs — do not hand-edit.
// Re-run that script after changing scripts/data/warehouse-codes.csv.
//
// whCode -> this code's row position in the hospital's original 4-sheet requisition (see that
// script's own header comment). Used ONLY to sort printWarehouseRequestByCategory's printed
// rows into the same order staff already know from the Google Sheet (AppContext.tsx) — never
// read for anything else (matching/validation stays whCode itself, this is display order only).
export const WAREHOUSE_SHEET_ORDER: Record<string, number> = {
${entriesStr}
};
`;

writeFileSync(OUT_FILE, out, 'utf8');
console.log(`Wrote ${entries.length} codes to ${OUT_FILE} (${codes.length - entries.length} duplicate code(s) in the source sheet skipped)`);
