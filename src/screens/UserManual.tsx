interface Section { id: string; icon: string; title: string; summary: string; body: ReactNode }

const Tab = ({ children }: { children: ReactNode }) => <span className="um-tab">{children}</span>;
const Tip = ({ children }: { children: ReactNode }) => <div className="um-note um-note--tip"><b>💡 เคล็ดลับ</b><div>{children}</div></div>;
const Warn = ({ children }: { children: ReactNode }) => <div className="um-note um-note--warn"><b>⚠️ ระวัง</b><div>{children}</div></div>;
const Steps = ({ items }: { items: ReactNode[] }) => (
  <ol className="um-steps">{items.map((t, i) => <li key={i}><span className="um-n">{i + 1}</span><div>{t}</div></li>)}</ol>
);


/** Screenshots live in public/manual/ and are regenerated from the real UI by `npm run manual:shots`. */
export interface Shot { file: string; cap: string }
export const shotUrl = (file: string) => import.meta.env.BASE_URL + 'manual/' + file + '.jpg';
function Gallery({ title, shots }: { title: string; shots: Shot[] }) {
  const [zoom, setZoom] = useState<number | null>(null);
  return (
    <div className="um-gal" data-testid="manual-gallery">
      <div className="um-gal-t">📸 {title} <small>(แตะรูปเพื่อขยาย · เลื่อนดูทีละขั้น)</small></div>
      <div className="um-gal-strip">
        {shots.map((s, i) => (
          <figure key={s.file} className="um-fig">
            <button type="button" className="um-fig-btn" onClick={() => setZoom(i)} aria-label={'ขยายรูปขั้นที่ ' + (i + 1)}>
              <img src={shotUrl(s.file)} alt={'ขั้นที่ ' + (i + 1) + ': ' + s.cap} data-shot={s.file} loading="lazy" decoding="async" />
              <span className="um-fig-n">{i + 1}</span>
            </button>
            <figcaption><b>{i + 1}.</b> {s.cap}</figcaption>
          </figure>
        ))}
      </div>
      {zoom !== null && (
        <div className="um-zoom" role="dialog" aria-modal="true" aria-label="รูปขยาย" onClick={() => setZoom(null)}>
          <img src={shotUrl(shots[zoom]!.file)} alt={shots[zoom]!.cap} />
          <div className="um-zoom-cap"><b>{zoom + 1}/{shots.length}</b> {shots[zoom]!.cap}</div>
          <button type="button" className="um-zoom-x" aria-label="ปิดรูป">✕</button>
        </div>
      )}
    </div>
  );
}

