export default function UserManual({ onClose, initialId }: { onClose: () => void; initialId?: string | undefined }) {
  const [active, setActive] = useState(MANUAL_SECTIONS.some((s) => s.id === initialId) ? (initialId as string) : MANUAL_SECTIONS[0].id);
  const scroller = useRef<HTMLDivElement>(null);
  const closeBtn = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    closeBtn.current?.focus();
    if (initialId) { const el = scroller.current?.querySelector('#um-' + initialId); if (el && 'scrollIntoView' in el) (el as HTMLElement).scrollIntoView({ block: 'start' }); }
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);

  const jump = (id: string) => {
    setActive(id);
    const el = scroller.current?.querySelector('#um-' + id);
    if (el && 'scrollIntoView' in el) (el as HTMLElement).scrollIntoView({ behavior: 'smooth', block: 'start' });
  };

  // Portal to <body>: opened from the "เพิ่มเติม" tab it would otherwise sit under the bottom nav (a stacking context of its own).
  return createPortal(
    <div className="um-overlay" role="dialog" aria-modal="true" aria-label="คู่มือการใช้งานแอป" data-testid="user-manual">
      <header className="um-head">
        <div className="um-head-row">
          <div className="um-head-title"><span>📖 คู่มือการใช้งาน</span><small>Krongpinang Hospital · Drug Substock</small></div>
          <button ref={closeBtn} type="button" className="um-close" onClick={onClose} aria-label="ปิดคู่มือ">✕ ปิด</button>
        </div>
        <nav className="um-toc" aria-label="สารบัญ">
          {MANUAL_SECTIONS.map((s) => (
            <button key={s.id} type="button" className="um-chip" data-active={active === s.id ? '1' : '0'} onClick={() => jump(s.id)}>
              <span aria-hidden="true">{s.icon}</span> {s.title.split(' (')[0]}
            </button>
          ))}
        </nav>
      </header>
      <div className="um-scroll" ref={scroller}>
        <div className="um-wrap">
          <div className="um-hero">
            <div className="um-hero-t">แอปนี้ช่วยอะไร?</div>
            <p>คุมยอดยา <b>substock</b> และ<b>ชั้นวางหน้างาน</b> ให้ตรงกับความเป็นจริง — ตัดยอดตามที่ HOSxP จ่ายจริง เติมหน้างานตาม FEFO รับยาเข้า/คืน/ปรับยอดพร้อมเหตุผล และทุกรายการตรวจย้อนหลังได้ใน Audit log</p>
          </div>
          {MANUAL_SECTIONS.map((s, i) => (
            <section key={s.id} id={'um-' + s.id} className="um-sec" aria-labelledby={'umh-' + s.id}>
              <h3 id={'umh-' + s.id} className="um-h"><span className="um-ico" aria-hidden="true">{s.icon}</span><span><span className="um-no">{i + 1}.</span> {s.title}<small>{s.summary}</small></span></h3>
              <div className="um-body">{s.body}</div>
            </section>
          ))}
          <div className="um-end">จบคู่มือ · หากพบจุดที่ไม่ตรงกับหน้าจอจริง แจ้งผู้ดูแลระบบ</div>
        </div>
      </div>
    </div>,
    document.body,
  );
}
